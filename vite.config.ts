import inertia from '@inertiajs/vite';
import { wayfinder } from '@laravel/vite-plugin-wayfinder';
import babel from '@rolldown/plugin-babel';
import tailwindcss from '@tailwindcss/vite';
import react, { reactCompilerPreset } from '@vitejs/plugin-react';
import laravel from 'laravel-vite-plugin';
import { bunny } from 'laravel-vite-plugin/fonts';
import { defineConfig } from 'vite';

export default defineConfig(({ command }) => ({
    plugins: [
        laravel({
            input: ['resources/css/app.css', 'resources/js/app.tsx'],
            refresh: true,
            fonts: [
                bunny('Public Sans', {
                    subsets: ['latin', 'latin-ext'],
                    weights: [400, 500, 600],
                    optimizedFallbacks: false,
                }),
                // Starter font; typography follows Figma in F-006. Fallback
                // metric optimisation would need the optional `fontaine` dep.
                bunny('Instrument Sans', {
                    weights: [400, 500, 600],
                    optimizedFallbacks: false,
                }),
            ],
        }),
        inertia(),
        react(),
        babel({
            presets: [reactCompilerPreset()],
        }),
        tailwindcss(),
        // Wayfinder route/action types are generated by the PHP stage
        // (`composer wayfinder`) before a production build; the Node build
        // must not assume PHP is available. The dev server regenerates them
        // on route/controller changes.
        command === 'serve' &&
            process.env.WAYFINDER_EXTERNAL !== 'true' &&
            wayfinder({
                formVariants: true,
            }),
    ],
    server: {
        host: '0.0.0.0',
        port: Number(process.env.VITE_PORT ?? 5173),
        strictPort: true,
        allowedHosts: ['localhost', '127.0.0.1'],
        hmr: { host: 'localhost' },
        watch: {
            ignored: [
                '**/.agents/**',
                '**/.claude/**',
                '**/.cursor/**',
                '**/.junie/**',
                '**/vendor/**',
            ],
        },
    },
}));
